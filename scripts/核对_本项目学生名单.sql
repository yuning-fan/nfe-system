  select p.id, p.full_name, p.status as acct_status,
         (select count(*) from public.student_enrollments e where e.student_id = p.id) as enr_cnt
  from public.profiles p where p.role = 'student'
),
-- ① 名单上有、系统里没有 → 需要补建
