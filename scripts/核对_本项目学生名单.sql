  select '③ 已匹配', r.name, r.status,
         case d.acct_status when 1 then '正常' else '禁用' end, d.enr_cnt::text
  from roster r join db d on d.full_name = r.name
),
d2 as (
  select '④ 汇总', '名单人数', (select count(*)::text from roster),
         '系统学生数', (select count(*)::text from db)
)
